type DictionaryKey = keyof typeof dictionaries.en;

export function useI18n() {
  const locale = useUiStore((state) => state.locale);
  const setLocale = useUiStore((state) => state.setLocale);

  const t = useCallback(
    (key: DictionaryKey, variables?: Record<string, string | number>) => {
      const template = dictionaries[locale][key] ?? dictionaries.en[key];
      if (!variables) return template;
      return Object.entries(variables).reduce(
        (value, [name, replacement]) => value.split(`{${name}}`).join(String(replacement)),
        template as string,
      );
    },
    [locale],
  );

  const statusLabel = useCallback(
    (status: string) => statuses[locale][status as keyof typeof statuses.en] ?? status.replace(/_/g, ' '),
    [locale],
  );

  return { locale, setLocale, t, statusLabel };
}

